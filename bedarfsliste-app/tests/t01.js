// Grundtest: leere Datei startet, ein Bedarf läuft per Bedienung durch alle Phasen, nichts wird aus dem Internet geladen
const { chromium, ok, open, finish } = require('./lib');
(async () => {
  const b = await chromium.launch();
  const p = await open(b, { fakefs: false });
  ok(await p.$eval('#list-body', e => e.textContent.includes('Noch keine Bedarfe')), 'leere Liste mit Hinweis');
  await p.click('button[data-act="new"]');
  await p.keyboard.type('Defibrillator Test');
  ok(await p.$eval('#d-title', e => e.textContent) === 'Defibrillator Test', 'Titel wird beim Tippen übernommen');
  await p.fill('input[data-p="gliederung"]', 'Paderborn');
  await p.fill('input[data-p="summe"]', '1.500'); await p.press('input[data-p="summe"]', 'Tab');
  let r = await p.evaluate(() => [D.bedarfe[0].summe, document.querySelector('input[data-p="summe"]').value, document.querySelector('#d-status').textContent]);
  ok(r[0] === 1500 && r[1] === '1.500', 'Summe deutsch eingegeben: ' + r[0] + ' / ' + r[1]);
  ok(r[2].includes('Es fehlt: Ortsführungskreis, Angebot, Fachreferat, Verwaltung'), 'Stand nennt, was in der Freigabe fehlt: ' + r[2]);
  await p.fill('input[data-p="summe"]', 'abc'); await p.press('input[data-p="summe"]', 'Tab');
  r = await p.evaluate(() => [D.bedarfe[0].summe, document.querySelector('input[data-p="summe"]').value]);
  ok(r[0] === 1500 && r[1] === '1.500', 'keine Zahl: nicht übernommen, alter Wert zurück');
  await p.fill('input[data-p="summe"]', '800'); await p.press('input[data-p="summe"]', 'Tab');
  ok((await p.$eval('#fr-body', e => e.textContent)).split('nicht nötig, unter 1.000 €').length === 3, 'unter 1.000 €: Fachreferat und Verwaltung nicht nötig');
  await p.click('[data-p="freigabe.ofk.st"][data-v="angefragt"]');
  ok(await p.evaluate(() => D.bedarfe[0].freigabe.ofk.angefragt === today()), 'angefragt: Datum wird gesetzt');
  await p.click('[data-p="freigabe.ofk.st"][data-v="ok"]');
  await p.click('[data-p="freigabe.angebot.st"][data-v="ok"]');
  ok((await p.$eval('#d-status', e => e.textContent)).includes('Förderplan aufstellen'), 'Freigabe vollständig → Förderplan aufstellen');
  await p.click('button[data-act="add-foe"]');
  await p.keyboard.type('Sparkasse X');
  await p.fill('input[data-p="betrag"]', '800');
  ok((await p.$eval('#d-status', e => e.textContent)).includes('Anträge stellen'), 'Förderer geplant → Anträge stellen');
  await p.click('[data-p="status"][data-v="zugesagt"]');
  r = await p.evaluate(() => { const f = D.bedarfe[0].foerderer[0]; return [f.zugesagt, f.beantragtAm === today(), D.bedarfe[0].nach.ueb.mit.includes(f.id), document.querySelector('#d-status').textContent]; });
  ok(r[0] === 800 && r[1] && r[2], 'zugesagt: Betrag, Datum und Spendenübergabe vorbelegt');
  ok(r[3].includes('Geldeingang offen'), 'Stand: Geldeingang offen');
  await p.click('button[data-act="geld"]'); await p.click('button[data-act="geld-ok"]');
  r = await p.evaluate(() => [D.bedarfe[0].foerderer[0].eingegangen, document.querySelector('#d-status').textContent, document.querySelector('#d-steps .cur').textContent]);
  ok(r[0] === 800 && r[1].includes('Spendenübergabe') && r[1].includes('Pressemitteilung') && r[2] === 'Nacharbeit', 'Geld eingegangen → Phase Nacharbeit: ' + r[1]);
  await p.click('[data-p="nach.ueb.st"][data-v="erledigt"]'); await p.click('[data-p="nach.pm.st"][data-v="veroeff"]');
  ok((await p.$eval('#d-status', e => e.textContent)).includes('Alles erledigt'), 'Nacharbeit erledigt → abgeschlossen');
  await p.click('button[data-act="back"]');
  ok(await p.$eval('tr.grp.ph-fertig', e => e.textContent.includes('Phase 4 · Abgeschlossen')), 'Liste gruppiert: Phase 4');
  await p.click('#list-body tr[data-id] button.prio');
  await p.click('#pmenu button[data-v="hoch"]');
  ok(await p.evaluate(() => D.bedarfe[0].prio === 'hoch' && UI.view === 'list'), 'Priorität in der Liste geändert, Liste bleibt offen');
  r = await p.evaluate(() => [...document.querySelectorAll('#list-body tr[data-id] td:nth-child(6) .mi')].map(e => e.className.replace('mi ', '') + ':' + e.textContent));
  ok(r.join(',') === 'ok:✓OFK,ok:✓Angebot,na:–Fachreferat,na:–Verwaltung', 'Freigabe in der Liste untereinander: ' + r.join(','));
  await p.click('#list-body tr[data-id]'); await p.click('button[data-act="archive"]');
  ok(await p.evaluate(() => D.bedarfe[0].archiv && !document.querySelector('#list-body tr[data-id]')), 'archiviert: aus der Liste verschwunden');
  await p.click('#toasts button.link');
  ok(await p.evaluate(() => !D.bedarfe[0].archiv && !!document.querySelector('#list-body tr[data-id]')), 'Rückgängig holt ihn zurück');
  await p.screenshot({ path: 'liste.png' });
  ok(!p.reqs.length, 'keine Anfragen ins Internet' + (p.reqs.length ? ': ' + p.reqs.join(', ') : ''));
  await finish(b, [p]);
})();
